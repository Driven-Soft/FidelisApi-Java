CREATE TABLE FIDELIS_USUARIO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(75) NOT NULL UNIQUE,
    senha VARCHAR(100) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_criacao DATE NOT NULL,

    FIDELIS_TUTOR_id BIGINT,
    FIDELIS_CLINICA_id BIGINT,

    CONSTRAINT FK_USUARIO_TUTOR FOREIGN KEY (FIDELIS_TUTOR_id)
        REFERENCES FIDELIS_TUTOR(id),

    CONSTRAINT FK_USUARIO_CLINICA FOREIGN KEY (FIDELIS_CLINICA_id)
        REFERENCES FIDELIS_CLINICA(id),

    CONSTRAINT CHK_USUARIO_PERFIL CHECK (perfil IN ('CLINICA','TUTOR')),

    CONSTRAINT CHK_USUARIO_VINCULO CHECK (
        (perfil = 'CLINICA' AND FIDELIS_CLINICA_id IS NOT NULL AND FIDELIS_TUTOR_id IS NULL)
        OR
        (perfil = 'TUTOR' AND FIDELIS_TUTOR_id IS NOT NULL AND FIDELIS_CLINICA_id IS NULL)
    )
);