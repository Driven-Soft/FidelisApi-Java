CREATE TABLE FIDELIS_CLINICA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cnpj VARCHAR(18) NOT NULL UNIQUE,
    telefone VARCHAR(15) NOT NULL,
    email VARCHAR(75) NOT NULL UNIQUE,
    endereco VARCHAR(255) NOT NULL
);

CREATE TABLE FIDELIS_TUTOR (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR(14) NOT NULL UNIQUE,
    nome VARCHAR(75) NOT NULL,
    email VARCHAR(75) NOT NULL UNIQUE,
    senha VARCHAR(100) NOT NULL,
    telefone VARCHAR(15) NOT NULL,
    endereco VARCHAR(255) NOT NULL,
    data_criacao DATE NOT NULL
);

CREATE TABLE FIDELIS_VETERINARIO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cmvv VARCHAR(13) NOT NULL UNIQUE,
    nome VARCHAR(75) NOT NULL,
    email VARCHAR(75) NOT NULL UNIQUE,
    senha VARCHAR(100) NOT NULL,
    especialidade VARCHAR(50) NOT NULL,
    data_criacao DATE NOT NULL,
    FIDELIS_CLINICA_id BIGINT NOT NULL,
    CONSTRAINT FK_VET_CLINICA FOREIGN KEY (FIDELIS_CLINICA_id)
        REFERENCES FIDELIS_CLINICA(id)
);

CREATE TABLE FIDELIS_PET (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(30) NOT NULL,
    especie VARCHAR(20) NOT NULL,
    raca VARCHAR(20) NOT NULL,
    sexo VARCHAR(1) NOT NULL,
    data_nascimento DATE NOT NULL,
    status VARCHAR(1) NOT NULL,
    foto_url VARCHAR(255),

    FIDELIS_TUTOR_id BIGINT NOT NULL,
    FIDELIS_CLINICA_id BIGINT NOT NULL,

    CONSTRAINT FK_PET_TUTOR FOREIGN KEY (FIDELIS_TUTOR_id)
        REFERENCES FIDELIS_TUTOR(id),

    CONSTRAINT FK_PET_CLINICA FOREIGN KEY (FIDELIS_CLINICA_id)
        REFERENCES FIDELIS_CLINICA(id)
);

CREATE TABLE FIDELIS_CONSULTA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    data_hora TIMESTAMP NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    diagnostico VARCHAR(5000),
    observacoes VARCHAR(5000),
    data_retorno DATE,

    FIDELIS_VETERINARIO_id BIGINT NOT NULL,
    FIDELIS_PET_id BIGINT NOT NULL,

    CONSTRAINT FK_CONSULTA_VET FOREIGN KEY (FIDELIS_VETERINARIO_id)
        REFERENCES FIDELIS_VETERINARIO(id),

    CONSTRAINT FK_CONSULTA_PET FOREIGN KEY (FIDELIS_PET_id)
        REFERENCES FIDELIS_PET(id)
);

